import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { startConsoleFixture } from './console-ui-fixture.mjs';
const require = createRequire(import.meta.url), { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const executablePath = [path.join(process.env.PROGRAMFILES || '', 'Google/Chrome/Application/chrome.exe'), path.join(process.env['PROGRAMFILES(X86)'] || '', 'Microsoft/Edge/Application/msedge.exe')].find(fs.existsSync);
const fixture = await startConsoleFixture();
const backgrounds = new Map([['group:20009', '群聊背景'], ['private:20012', '私聊背景'], ['private:20015', '只有背景记录的会话']]);
const writes = [], errors = [], artifact = path.resolve('state/audits/initial-prompt-picker-20261030');
fs.mkdirSync(artifact, { recursive: true });
let browser, slow = false, release;
try {
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(8000);
  page.on('pageerror', error => errors.push(error.message));
  const html = await (await fetch(fixture.url)).text();
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== fixture.url) return route.abort();
    if (url.pathname === '/') return route.fulfill({ contentType: 'text/html', body: html });
    return route.continue();
  });
  await page.route('**/api/socialV2/initial-prompt*', async route => {
    const request = route.request(), key = new URL(request.url()).searchParams.get('key');
    let value;
    if (request.method() === 'POST') {
      const body = request.postDataJSON(); writes.push(body);
      if (body.delete || !body.text) backgrounds.delete(body.key); else backgrounds.set(body.key, body.text);
      value = { ok: true, key: body.key, deleted: !backgrounds.has(body.key), chars: backgrounds.get(body.key)?.length || 0, maxChars: 2000 };
    } else if (key) {
      if (slow && key === 'group:20009') await new Promise(resolve => { release = resolve; });
      value = { ok: true, key, exists: backgrounds.has(key), text: backgrounds.get(key) || '', maxChars: 2000, writable: true };
    } else value = { ok: true, entries: [...backgrounds].map(([key, text]) => ({ key, chars: text.length })), maxChars: 2000, writable: true };
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify(value) });
  });
  await page.goto(fixture.url + '/#setting-c-2');
  const picker = page.locator('#v2InitPromptKey');
  assert.equal(await picker.evaluate(el => el.tagName), 'SELECT', 'Use a real session selector, not a value-filtered datalist');
  await picker.locator('xpath=ancestor::details[1]').locator(':scope > summary').click();
  await page.waitForFunction(() => document.querySelector('#v2InitPromptKey option[value="private:20015"]'));
  const values = await picker.locator('option').evaluateAll(nodes => nodes.map(el => el.value));
  assert(values.includes('group:20009') && values.includes('private:20012'));
  assert.equal(new Set(values).size, values.length);
  await picker.selectOption('group:20009');
  await page.waitForFunction(() => document.getElementById('v2InitPromptText').value === '群聊背景');
  await picker.selectOption('private:20012');
  await page.waitForFunction(() => document.getElementById('v2InitPromptText').value === '私聊背景');
  assert(values.every(value => !value || value === '__manual__' || /^(private|group):\d+$/.test(value)));
  await page.locator('#v2InitPromptText').fill('私聊的新背景');
  page.once('dialog', dialog => dialog.dismiss());
  await picker.selectOption('group:20009');
  assert.equal(await picker.inputValue(), 'private:20012');
  assert.equal(await page.locator('#v2InitPromptText').inputValue(), '私聊的新背景');
  await page.locator('#v2InitPromptSave').click();
  await page.locator('#v2InitPromptMsg').filter({ hasText: '已保存' }).waitFor();
  assert.deepEqual(writes.at(-1), { key: 'private:20012', text: '私聊的新背景' });
  assert.equal(backgrounds.get('group:20009'), '群聊背景');
  slow = true;
  const delayedRequest = page.waitForRequest(request => request.url().includes('initial-prompt?key=group%3A20009'));
  await picker.selectOption('group:20009');
  await delayedRequest;
  await picker.selectOption('private:20012');
  await page.waitForFunction(() => document.getElementById('v2InitPromptText').value === '私聊的新背景');
  release?.(); slow = false;
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#v2InitPromptText').inputValue(), '私聊的新背景', 'A late response must not overwrite the newly selected conversation');
  await picker.selectOption('__manual__');
  await page.locator('#v2InitPromptManualKey').fill('private:20017');
  await page.locator('#v2InitPromptLoad').click();
  await page.locator('#v2InitPromptText:enabled').waitFor({ state: 'attached' });
  await page.locator('#v2InitPromptText').fill('新会话背景');
  await page.locator('#v2InitPromptSave').click();
  await page.locator('#v2InitPromptMsg').filter({ hasText: '已保存' }).waitFor();
  assert.equal(backgrounds.get('private:20017'), '新会话背景');
  await page.locator('#section-setting-c-2 > details').first().screenshot({ path: path.join(artifact, 'picker-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.locator('#section-setting-c-2 > details').first().screenshot({ path: path.join(artifact, 'picker-mobile.png') });
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(artifact, 'result.json'), JSON.stringify({ ok: true, flows: ['all sessions', 'saved-only sessions', 'switch and auto-load', 'draft cancellation', 'save scope', 'late response', 'manual new session', 'desktop/mobile'], errors }, null, 2));
  console.log('Initial prompt selector: all sessions, scoped reads/writes, draft guard, late responses, manual entry and mobile passed');
} finally { release?.(); await browser?.close(); await fixture.close(); }
