import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
// Retain the tested fetch protocol without installing the old gateway's host
// dependencies into a DSH profile, where they can shadow the current runtime.
export async function buildDshClient({check=false}={}){
 const require=createRequire(path.join(root,'package.json'));
 const entry=path.relative(root,require.resolve('@deepseek-ai/dsh-host-apiproxy/client')).replaceAll('\\','/');
 const result=await build({absWorkingDir:root,entryPoints:[entry],bundle:true,format:'esm',platform:'node',target:'node24',external:['zod'],write:false,metafile:true,legalComments:'inline',charset:'utf8'});
 if(Object.values(result.metafile.outputs).flatMap(output=>output.imports).some(item=>item.external&&item.path!=='zod'))throw Error('Unexpected dependency in bundled DSH client');
 const file=path.join(root,'src/vendor/dsh-api-client.mjs');
 // esbuild follows node_modules junctions. Keep source labels independent of
 // the checkout location and npm/pnpm's physical dependency layout.
 const source=result.outputFiles[0].text.replace(/^\/\/ .*?(@deepseek-ai\/dsh-host-apiproxy\/[^\r\n]+)$/gm,'// $1');
 const content='// Generated by scripts/build-dsh-client.mjs; do not edit.\n// @deepseek-ai/dsh-host-apiproxy 0.1.1-rc.2, MIT (c) 2026 DeepSeek. See LICENSE.deepseek.\n'+source;
 const changed=!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==content;
 if(changed&&!check){fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,content);}
 return {file,changed,bytes:Buffer.byteLength(content)};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const check=process.argv.includes('--check'),result=await buildDshClient({check});
 console.log(JSON.stringify({...result,check}));if(check&&result.changed)process.exitCode=1;
}
