import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { startConsoleFixture } from './console-ui-fixture.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || [path.join(process.env.PROGRAMFILES || '', 'Google/Chrome/Application/chrome.exe'), path.join(process.env['PROGRAMFILES(X86)'] || '', 'Microsoft/Edge/Application/msedge.exe')].find(existsSync);
const fixture = await startConsoleFixture();
const artifact = path.resolve('state/audits/memory-responsibilities-20261029'); mkdirSync(artifact, { recursive: true });
let browser; const errors = [];
try {
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.route('**/*', route => new URL(route.request().url()).origin === fixture.url ? route.continue() : route.abort());
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.url + '/#setting-c-1');
  await page.locator('#v2AffairsMsg').filter({ hasText: '已加载' }).waitFor();
  assert.equal(await page.locator('#v2AffairEditor').evaluate(e=>e.open),false);
  assert.equal(await page.locator('#v2AffairHistory').count(),0);
  await page.locator('#v2AffairsNew').click();
  assert.equal(await page.locator('#v2AffairEditor').evaluate(e=>e.open),true);
  await page.locator('#v2AffairTitle').fill('周五一起吃饭 <img src=x onerror=alert(1)>');
  await page.locator('#v2AffairDetail').fill('对方随口提到的约定，不自动创建提醒。');
  await page.locator('#v2AffairNextAction').fill('下次聊到时确认时间');
  await page.locator('#v2AffairSource').fill('2026-10-29 用户原话');
  await page.locator('#v2AffairsSave').click();
  await page.locator('#v2AffairsMsg').filter({ hasText: '已保存' }).waitFor();
  const key = await page.locator('#v2AffairsKey').inputValue();
  let item = fixture.affairsStore.list({ key }).items[0];
  assert.ok(item.title.includes('<img'));
  assert.equal(await page.locator('#v2AffairsList img').count(), 0);
  assert.ok((await page.locator('#v2AffairsPreview').textContent()).includes(item.id));
  assert.equal(await page.locator('#v2AffairEditor').evaluate(e=>e.open),false);
  await page.locator('[data-affair-done]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-affair-done]'));
  assert.equal(fixture.affairsStore.list({ key }).total, 0);
  await page.locator('#v2AffairsFilter').selectOption('all');
  await page.locator('#v2AffairsList [data-affair-id]').click();
  assert.equal(await page.locator('#v2AffairStatus').inputValue(), 'done');
  assert.equal(fixture.affairsStore.list({key,status:'all'}).items[0].history.length,1);
  item = fixture.affairsStore.list({ key, status: 'all' }).items[0];
  fixture.affairsStore.upsert({ key, id: item.id, expectedRevision: item.revision, title: '周五聚餐：确认餐厅' });
  await page.locator('#v2AffairDetail').fill('我的未保存内容'); await page.locator('#v2AffairsSave').click();
  await page.locator('#v2AffairsMsg').filter({ hasText: '事务已更新' }).waitFor();
  assert.equal(await page.locator('#v2AffairDetail').inputValue(), '我的未保存内容');
  await page.locator('#v2AffairEditor').screenshot({path:path.join(artifact,'affairs-editor.png')});
  await page.locator('#v2AffairsCancel').click();
  await page.locator('#v2AffairsLoad').click();
  await page.locator('#v2AffairsList').filter({hasText:'周五聚餐：确认餐厅'}).waitFor();
  await page.screenshot({ path: path.join(artifact, 'memory-console-desktop.png'), fullPage: true });
  await page.locator('#v2AffairsPanel').screenshot({ path: path.join(artifact, 'affairs-panel-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: path.join(artifact, 'memory-console-mobile.png'), fullPage: true });
  await page.locator('#v2AffairsPanel').screenshot({ path: path.join(artifact, 'affairs-panel-mobile.png') });
  assert.deepEqual(errors, []); assert.deepEqual(fixture.unknownRequests, []);
  writeFileSync(path.join(artifact, 'console-result.json'), JSON.stringify({ ok: true, flows: ['create', 'read', 'preview', 'complete', 'history', 'conflict', 'xss', 'mobile'], errors }, null, 2));
  console.log('Memory console: create/read/edit/complete/history/preview/conflict/XSS/mobile passed');
} finally { await browser?.close(); await fixture.close(); }
