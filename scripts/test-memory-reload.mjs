import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPluginHost } from '../src/plugin-host.js';
test('memory hot reload refreshes affair, document and window helper modules together', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'whale-memory-reload-')), original = fileURLToPath(new URL('../plugins/qq-components/', import.meta.url));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'package.json'), '{"type":"module"}');
  for (const id of ['ctx-memory-store', 'ctx-memory-context']) fs.cpSync(path.join(original, id), path.join(root, 'plugins', 'qq-components', id), { recursive: true });
  const host = createPluginHost({ root, startTimers: false }); t.after(() => host.dispose());
  await host.loadAll(); assert.deepEqual(host.summary().warnings, []);
  host.callService('affairs', 'upsert', { key: 'private:1', title: '事务热加载', status: 'doing' });
  assert.ok(host.callService('affairs', 'context', { key: 'private:1' }).text.includes('事务热加载'));
  const affairFile = path.join(root, 'plugins/qq-components/ctx-memory-store/affairs.mjs');
  fs.writeFileSync(affairFile, fs.readFileSync(affairFile, 'utf8').replace('const block = `[', 'const block = `[热更新事务｜'));
  await host.reload('ctx-memory-store');
  assert.ok(host.callService('affairs', 'context', { key: 'private:1' }).text.includes('热更新事务'));
  const sectionFile = path.join(root, 'plugins/qq-components/ctx-memory-store/sections.mjs');
  fs.writeFileSync(sectionFile, fs.readFileSync(sectionFile, 'utf8').replace('重要事实｜本会话逐条记录', '热更新事实｜本会话逐条记录'));
  await host.reload('ctx-memory-context');
  assert.ok(host.collectPromptBlocks({ st: {}, persistentMemory: { text: '【重要事实】\n- 来源事实' } }).join('').includes('热更新事实'));
  assert.ok(host.callService('lightMemory', 'window', { st: { recentMessages: [{ sender: '甲' }], memberImpressions: { 甲: { traits: ['窗口行为'] } } } }).甲);
  const windowFile = path.join(root, 'plugins/qq-components/ctx-memory-context/light-window.mjs');
  fs.writeFileSync(windowFile, fs.readFileSync(windowFile, 'utf8').replace('return Object.fromEntries(', 'return {} || Object.fromEntries('));
  await host.reload('ctx-memory-context');
  assert.deepEqual(host.callService('lightMemory', 'window', { st: { recentMessages: [{ sender: '甲' }], memberImpressions: { 甲: {} } } }), {});
  assert.deepEqual(host.summary().warnings, []);
});
