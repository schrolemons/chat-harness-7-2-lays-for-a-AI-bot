// 记忆更新插件：定期重写持久化记忆（客观陈述 / 重要信息 / 用户画像 / 日记）。
// 和 self-review 的分工：这里只写记忆，不改代码、不改配置、不发 QQ。

export function createPlugin(ctx) {
  const maxChars = Math.max(800, Number((ctx.config || {}).maxChars) || 4000);
  return {
    hooks: {
      beforePrompt(payload) {
        if (String(payload?.reason || '') !== 'memoryWrite') return '';
        return [
          '【记忆更新｜只写记忆，不发 QQ】',
          '现在更新你这个会话的持久化记忆文件（覆盖旧内容）。基于最近的聊天、轻量记忆和上文，输出**完整的新记忆**，严格用下面的格式（标签保留）：',
          '<MEMORY>',
          '【客观陈述】',
          '- （以可核对的行为和经历为主：谁说了什么、做了什么、一起完成或约定了什么；写清结果，不推测动机）',
          '【重要信息】',
          '- （需要长期记住的客观信息：明确约定、重要事件、身份事实、群规；个人偏好、回避项和细腻感受留给人物档案）',
          '【用户画像】',
          '- （按人记录可回溯的行为轨迹与共同经历，例如某人做过什么、参与了什么；不在这里扩写性格猜测、喜好、回避/未做事项或感性评价）',
          '【日记】',
          '（用第一人称写日记日期对应的时间窗：XX 日日记只记录前一日 22:00 至 XX 日当晚 22:00 发生的事；按消息时间归属，不能把午夜当作日界，也不要混入时间窗前的旧事。用 1~5 句口语化写经历、感受和后续想法；不要把自己的感受写成他人的客观性格）',
          '</MEMORY>',
          `要求：简洁准确、不编造；总长不超过 ${maxChars} 字；**不要发任何 QQ 消息、不要调用发送工具**；输出这段后直接收尾。`
        ].join('\n');
      }
    }
  };
}
